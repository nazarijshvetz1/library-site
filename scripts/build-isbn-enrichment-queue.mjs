import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const privateRoot = path.join(projectRoot, ".migration-private");
const snapshotPath = path.join(privateRoot, "isbn-live-snapshot-20260829.json");
const candidatePaths = [
  path.join(privateRoot, "isbn-url-candidates.json"),
  path.join(privateRoot, "isbn-yakaboo-candidates.json"),
  path.join(privateRoot, "isbn-official-candidates.json"),
];
const outputPath = path.join(projectRoot, "lib", "isbn-enrichment-queue.ts");
const reportPath = path.join(privateRoot, "isbn-enrichment-queue-report.json");

const snapshot = JSON.parse(await readFile(snapshotPath, "utf8"));
const existing = new Map(
  (snapshot.existingIsbns ?? []).map((item) => [compactIsbn(item.isbn), String(item.materialId)]),
);
const snapshotQuantity = new Map(
  (snapshot.items ?? []).map((item) => [String(item.materialId), Math.max(0, Number(item.totalQuantity) || 0)]),
);
const raw = [];
for (const candidatePath of candidatePaths) {
  if (!existsSync(candidatePath)) continue;
  const document = JSON.parse(await readFile(candidatePath, "utf8"));
  const sourceName = path.basename(candidatePath);
  for (const item of document.records ?? document.items ?? document.candidates ?? []) {
    const candidate = adapt(item, sourceName);
    if (candidate) raw.push(candidate);
  }
}

const rejected = [];
const byMaterial = new Map();
for (const candidate of raw) {
  const list = byMaterial.get(candidate.materialId) ?? [];
  if (!list.some((item) => item.isbn === candidate.isbn)) list.push(candidate);
  byMaterial.set(candidate.materialId, list);
}
const singleMaterialCandidates = [];
for (const [materialId, candidates] of byMaterial) {
  if (candidates.length !== 1) {
    rejected.push({ reason: "conflicting_isbns_for_material", materialId, isbns: candidates.map((item) => item.isbn) });
    continue;
  }
  singleMaterialCandidates.push(candidates[0]);
}

const byIsbn = new Map();
for (const candidate of singleMaterialCandidates) {
  const list = byIsbn.get(candidate.isbn) ?? [];
  list.push(candidate);
  byIsbn.set(candidate.isbn, list);
}
const selected = [];
for (const candidate of singleMaterialCandidates) {
  const currentMaterialId = existing.get(candidate.isbn);
  if (currentMaterialId && currentMaterialId !== candidate.materialId) {
    rejected.push({ reason: "isbn_already_used", ...candidate, currentMaterialId });
    continue;
  }
  const duplicateCandidates = byIsbn.get(candidate.isbn) ?? [];
  if (new Set(duplicateCandidates.map((item) => item.materialId)).size > 1) {
    rejected.push({ reason: "isbn_matches_multiple_materials", ...candidate, materialIds: duplicateCandidates.map((item) => item.materialId) });
    continue;
  }
  selected.push(candidate);
}
selected.sort((a, b) => a.materialId.localeCompare(b.materialId, "en"));
const publicSelected = selected.map((candidate) => {
  const publicCandidate = { ...candidate };
  delete publicCandidate.totalQuantity;
  return publicCandidate;
});

const header = `export type VerifiedIsbnCandidate = {
  materialId: string;
  title: string;
  author: string;
  publicationYear: number | null;
  isbn: string;
  evidenceUrl: string;
  evidenceLabel: string;
};

// Generated by scripts/build-isbn-enrichment-queue.mjs from edition-specific
// evidence. Ambiguous editions, duplicate cards and title-only guesses stay out.
export const VERIFIED_ISBN_CANDIDATES = `;
await writeFile(
  outputPath,
  `${header}${JSON.stringify(publicSelected, null, 2)} as const satisfies readonly VerifiedIsbnCandidate[];\n`,
  "utf8",
);
await writeFile(
  reportPath,
  `${JSON.stringify({
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    sourceFiles: candidatePaths.filter(existsSync).map((value) => path.basename(value)),
    rawExactCandidates: raw.length,
    selected: selected.length,
    physicalCopies: selected.reduce((sum, item) => sum + (snapshotQuantity.get(item.materialId) ?? 0), 0),
    rejected,
  }, null, 2)}\n`,
  "utf8",
);
