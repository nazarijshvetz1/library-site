function adapt(item, sourceName) {
  const status = String(item.status ?? "").toLowerCase();
  if (!new Set(["exact", "exact_candidate", "verified", "exact_url_evidence"]).has(status)) return null;
  const materialId = String(item.materialId ?? item.material_id ?? "").trim();
  const title = String(item.title ?? item.catalog?.title ?? "").trim();
  const isbn = normalizeIsbn(item.isbn13 ?? item.proposedIsbn13 ?? item.isbn ?? "");
  const evidenceUrl = String(item.sourceUrl ?? item.evidenceUrl ?? item.url ?? item.evidence?.[0]?.url ?? "").trim();
  if (!/^CAT-\d{4,}$/.test(materialId) || !title || !isbn || !safeHttps(evidenceUrl)) return null;
  const yearValue = Number(item.year ?? item.publicationYear ?? item.catalogYear ?? item.catalog?.year ?? 0);
  return {
    materialId,
    title,
    author: String(item.author ?? item.catalog?.author ?? "").trim(),
    publicationYear: Number.isInteger(yearValue) && yearValue > 0 ? yearValue : null,
    isbn,
    evidenceUrl,
    evidenceLabel: evidenceLabel(evidenceUrl, sourceName),
    totalQuantity: Math.max(0, Number(item.totalQuantity ?? item.total_quantity ?? 0) || 0),
  };
}

function compactIsbn(value) {
  return String(value ?? "").replace(/[^0-9X]/gi, "").toUpperCase();
}

function normalizeIsbn(value) {
  const compact = compactIsbn(value);
  if (/^\d{13}$/.test(compact) && /^(?:978|979)/.test(compact) && validIsbn13(compact)) return compact;
  if (/^\d{9}[\dX]$/.test(compact) && validIsbn10(compact)) {
    const base = `978${compact.slice(0, 9)}`;
    const sum = [...base].reduce((total, digit, index) => total + Number(digit) * (index % 2 === 0 ? 1 : 3), 0);
    return `${base}${(10 - (sum % 10)) % 10}`;
  }
  return "";
}

function validIsbn13(value) {
  const sum = [...value].reduce((total, digit, index) => total + Number(digit) * (index % 2 === 0 ? 1 : 3), 0);
  return sum % 10 === 0;
}

function validIsbn10(value) {
  return [...value].reduce((sum, char, index) => sum + (char === "X" ? 10 : Number(char)) * (10 - index), 0) % 11 === 0;
}

function safeHttps(value) {
  try {
    const url = new URL(value);
    return url.protocol === "https:" && !url.username && !url.password;
  } catch {
    return false;
  }
}

function evidenceLabel(value, fallback) {
  try {
    return new URL(value).hostname.replace(/^www\./, "");
  } catch {
    return fallback;
  }
}
